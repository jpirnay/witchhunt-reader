"""THROWAWAY (TTF step 0): where each sampled Han glyph's outline lives in the FULL font file.

For every codepoint the bench samples (U+4E00..U+9FA5, step 41), the absolute byte offset and length
of its glyf record in SRC (a .ttf, or member INDEX of a .ttc), in sample order. The device reads exactly
these ranges from the same file on the SD card. usage: make_cjk_extents.py SRC INDEX OUT.h"""
import pathlib
import sys

from fontTools.ttLib import TTFont

src, index, out = sys.argv[1], int(sys.argv[2]), pathlib.Path(sys.argv[3])
font = TTFont(src, fontNumber=index) if index >= 0 else TTFont(src)
glyf_off = font.reader.tables["glyf"].offset  # absolute in the file, also for a .ttc member
loca = font["loca"]
order = font.getGlyphOrder()
cmap = font.getBestCmap()
rows = []
for cp in range(0x4E00, 0x9FA6, 41):
    name = cmap.get(cp)
    if name is None:
        continue
    gid = order.index(name)
    start, end = loca[gid], loca[gid + 1]
    rows.append((cp, glyf_off + start, end - start))
total = sum(r[2] for r in rows)
lines = ["// Generated by bench/ttf/make_cjk_extents.py. Do not commit.", "#pragma once", "#include <cstdint>",
         "struct CjkExtent { uint32_t cp; uint32_t offset; uint16_t length; };",
         f"static const CjkExtent kCjkExtents[{len(rows)}] = {{"]
lines += [f"  {{0x{cp:04X}, {off}u, {length}}}," for cp, off, length in rows]
lines += ["};", f"static constexpr uint32_t kCjkExtentCount = {len(rows)};"]
out.write_text("\n".join(lines) + "\n", encoding="ascii")
sectors = sum((off + length - 1) // 512 - off // 512 + 1 for _, off, length in rows if length)
print(f"{out}: {len(rows)} glyphs, {total} bytes of outline, mean {total / len(rows):.0f} B, {sectors / len(rows):.2f} sectors per glyph")
