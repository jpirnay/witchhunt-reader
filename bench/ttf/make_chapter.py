"""THROWAWAY (TTF step 0): a chapter of real prose for the kerning measurements.

Takes the first N characters of running text from one chapter file of the Moby-Dick fixture
(public domain) and writes it as a UTF-8 C string. usage: make_chapter.py EPUB MEMBER N OUT.h"""
import html
import pathlib
import re
import sys
import zipfile

epub, member, n, out = sys.argv[1], sys.argv[2], int(sys.argv[3]), pathlib.Path(sys.argv[4])
raw = zipfile.ZipFile(epub).read(member).decode("utf-8")
raw = re.sub(r"(?is)<(script|style|head)\b.*?</\1>", " ", raw)
text = html.unescape(re.sub(r"(?s)<[^>]+>", " ", raw))
text = re.sub(r"\s+", " ", text).strip()[:n]
lines = []
chunk = ""
for byte in text.encode("utf-8"):
    c = chr(byte)
    if byte < 0x20 or byte >= 0x7F:
        chunk += f"\\{byte:03o}"
    elif c in "\\\"":
        chunk += "\\" + c
    else:
        chunk += c
    if len(chunk) > 100:
        lines.append(f'    "{chunk}"')
        chunk = ""
if chunk:
    lines.append(f'    "{chunk}"')
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("// Generated by bench/ttf/make_chapter.py from the Moby-Dick fixture (public domain). Do not commit.\n"
               "#pragma once\nstatic const char kChapter[] =\n" + "\n".join(lines) + ";\n", encoding="ascii")
print(f"{out}: {len(text)} characters, {len(text.encode('utf-8'))} bytes")
