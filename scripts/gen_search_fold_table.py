#!/usr/bin/env python3
"""Writes lib/Utf8/SearchFoldTable.h: the base letter of each precomposed Latin letter, for book search.

For every code point in Latin-1 Supplement, Latin Extended-A/B (U+00C0-U+024F) and Latin Extended Additional
(U+1E00-U+1EFF): its lowercase form's canonical decomposition, first character, when that is an ASCII letter (é -> e,
Ő -> o, ạ -> a); 0 otherwise. Letters that do not decompose (ß, æ, ø, ł, đ, ...) are folded in code
(utf8BookSearchFold). Run from the repository root; commit the output.
"""
import unicodedata

RANGES = [(0x00C0, 0x024F), (0x1E00, 0x1EFF)]


def base_of(cp):
    lower = chr(cp).lower()
    if len(lower) != 1:
        return 0
    first = unicodedata.normalize("NFD", lower)[0]
    return ord(first) if "a" <= first <= "z" and first != lower else 0


def table(lo, hi):
    values = [base_of(cp) for cp in range(lo, hi + 1)]
    lines = []
    for i in range(0, len(values), 16):
        row = ", ".join("'%s'" % chr(v) if v else "0" for v in values[i:i + 16])
        lines.append("    " + row + ",")
    return "\n".join(lines)


out = ["// Generated by scripts/gen_search_fold_table.py. Do not edit by hand.",
       "#pragma once",
       "",
       "#include <cstdint>",
       "",
       "namespace SearchFoldTable {",
       ""]
for lo, hi in RANGES:
    out.append("// U+%04X-U+%04X: the ASCII base letter, 0 for none." % (lo, hi))
    out.append("constexpr uint32_t kFirst%04X = 0x%04X;" % (lo, lo))
    out.append("constexpr char kBase%04X[0x%X] = {" % (lo, hi - lo + 1))
    out.append(table(lo, hi))
    out.append("};")
    out.append("")
out.append("}  // namespace SearchFoldTable")
out.append("")
with open("lib/Utf8/SearchFoldTable.h", "w") as f:
    f.write("\n".join(out))
