#!/usr/bin/env python3
"""Generate lib/Epub/Epub/VerticalOrientationTable.h from Unicode's VerticalOrientation.txt (UAX #50).

Usage: python -I scripts/gen_vertical_orientation.py <VerticalOrientation.txt> [<out.h>]

The table is a sorted list of runs, each `start << 2 | class`, with adjacent runs of one class merged and R wherever
the file lists nothing (its @missing line). The class numbering is VerticalOrientation's in VerticalOrientation.h.
"""
import hashlib
import sys

EXPECTED_FIRST_LINE = "# VerticalOrientation-16.0.0.txt"
CLASSES = {"R": 0, "U": 1, "Tu": 2, "Tr": 3}
CODEPOINTS = 0x110000
DEFAULT_OUT = "lib/Epub/Epub/VerticalOrientationTable.h"


def parse(text):
    classes = [CLASSES["R"]] * CODEPOINTS  # the @missing line: R
    for line in text.splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        span, name = (part.strip() for part in body.split(";"))
        first, _, last = span.partition("..")
        lo = int(first, 16)
        hi = int(last or first, 16)
        for cp in range(lo, hi + 1):
            classes[cp] = CLASSES[name]
    return classes


def runs_of(classes):
    runs = []
    for cp, cls in enumerate(classes):
        if not runs or runs[-1][1] != cls:
            runs.append((cp, cls))
    return runs


def main():
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    raw = open(sys.argv[1], "rb").read()
    text = raw.decode("utf-8")
    if text.splitlines()[:1] != [EXPECTED_FIRST_LINE]:
        sys.exit(f"{sys.argv[1]}: first line is not '{EXPECTED_FIRST_LINE}'")
    runs = runs_of(parse(text))
    out_path = sys.argv[2] if len(sys.argv) == 3 else DEFAULT_OUT

    lines = [
        "// Unicode UAX #50 Vertical_Orientation, from VerticalOrientation-16.0.0.txt",
        f"// sha256 {hashlib.sha256(raw).hexdigest()}",
        "// Copyright Unicode, Inc.; used under the Unicode License v3 (https://www.unicode.org/license.txt).",
        "// Generated by scripts/gen_vertical_orientation.py; do not edit.",
        "//",
        "// Each entry is `start << 2 | class` (R 0, U 1, Tu 2, Tr 3); a run lasts until the next one starts.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        f"constexpr size_t kVerticalOrientationRunCount = {len(runs)};",
        "",
        "// clang-format off",
        "constexpr uint32_t kVerticalOrientationRuns[kVerticalOrientationRunCount] = {",
    ]
    row = []
    for start, cls in runs:
        row.append(f"0x{(start << 2) | cls:X}u,")
        if len(row) == 8:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("};")
    lines.append("// clang-format on")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
