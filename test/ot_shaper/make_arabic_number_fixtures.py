#!/usr/bin/env python3
"""Builds the Arabic number-sign fixture and records what HarfBuzz does with it.

    python -I test/ot_shaper/make_arabic_number_fixtures.py [--fonts-out test/fixtures/fonts] \
        [--header-out test/ot_shaper/ArabicNumberExpected.h]

A number sign (Unicode's Prepended_Concatenation_Mark of the Arabic blocks: U+0600-0605, the end of ayah U+06DD,
U+0890-0891, U+08E2) is drawn around the digits after it by the font's own lookups. The other Arabic fixtures
(make_arabic_fixtures.py) are cut to the words of their books and hold no sign, and adding one there would renumber
their glyphs; this one is cut on its own from the Font Manager's shipped NotoNaskhArabic Regular
(assets/sd-fonts/NotoNaskhArabic, checked against the sha256 below) to the signs, the three digit sets, beh and the
space, every layout feature kept:

- NotoNaskhArabic-Numbers-Regular.ttf, into --fonts-out.

Into --header-out it writes, in kArabicNumberShaping, the glyph runs of each sign followed by one to four digits of each
set, at scale 2133 and ppem 33, as the firmware writes them (IndicShaper's appendGlyphsLeftToRight): HarfBuzz 14.5's
run shaped right to left, script Arab, as make_arabic_fixtures.py records its words (its helpers do it), with its units
(the zero-advance glyphs and the advancing glyph after them) in reverse order. A sign and its digits are numbers, on an
even bidi level, so HarfBuzz in a bidi layout shapes them left to right; the script stops unless the reversed run
draws every glyph where HarfBuzz's left-to-right run draws it. The output is byte-identical on every run.

Needs fonttools 4.63.0 and uharfbuzz 0.56.2 (the versions lib/EpdFont/scripts/sd-fonts.yaml pins).
"""

import argparse
import hashlib
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_arabic_fixtures as fx  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "assets" / "sd-fonts" / "NotoNaskhArabic" / "NotoNaskhArabic-Regular.ttf"
SOURCE_SHA256 = "21acf0334143ff85a709ef1762694d083f9c70fb521fea9fae0e04cefd297f14"
FONT = "NotoNaskhArabic-Numbers-Regular.ttf"

SIGNS = [0x0600, 0x0601, 0x0602, 0x0603, 0x0604, 0x0605, 0x06DD, 0x0890, 0x0891, 0x08E2]
DIGIT_SETS = [list(range(0x30, 0x3A)), list(range(0x0660, 0x066A)), list(range(0x06F0, 0x06FA))]
BEH = 0x0628
SPACE = 0x20


def words():
    """Each sign with one to four digits of each set, the digits counting up from 1."""
    out = []
    for sign in SIGNS:
        for digits in DIGIT_SETS:
            for n in range(1, 5):
                out.append("".join(chr(c) for c in [sign] + digits[1:n + 1]))
    return out


def raw_run(font, text, direction):
    """HarfBuzz's glyphs of `text` as (glyph, x_advance, x_offset, y_offset), in its output order."""
    buf = fx.hb.Buffer()
    buf.add_str(text)
    buf.direction = direction
    buf.script = "Arab"
    fx.hb.shape(font, buf, {})
    return [(i.codepoint, p.x_advance, p.x_offset, p.y_offset) for i, p in zip(buf.glyph_infos, buf.glyph_positions)]


def units_reversed(run):
    """`run` (output order) with its units -- zero-advance glyphs and the advancing glyph after them -- last first."""
    units, current = [], []
    for k, glyph in enumerate(run):
        current.append(glyph)
        if glyph[1] != 0 or k + 1 == len(run):
            units.append(current)
            current = []
    return [g for unit in reversed(units) for g in unit]


def placements(run):
    """Where each glyph of `run` is drawn: (glyph, x, y), sorted."""
    pen, out = 0, []
    for glyph, advance, dx, dy in run:
        out.append((glyph, pen + dx, dy))
        pen += advance
    return sorted(out), pen


def as_expected(run):
    """`run` as ExpectedGlyph stores it, rounded as make_arabic_fixtures.shape() rounds."""
    return [(g, (a + 2) >> 2, fx.round_px(dx), -fx.round_px(dy)) for g, a, dx, dy in run]


def header_text(words_shaped):
    lines = [
        "#pragma once",
        "// Generated by test/ot_shaper/make_arabic_number_fixtures.py from test/fixtures/fonts/. Do not edit.",
        "// HarfBuzz 14.5.0 (uharfbuzz 0.56.2): the glyph runs of each Arabic number sign with one to four digits of each",
        "// digit set, shaped right to left, script Arab, at scale 2133 and ppem 33, then written left to right: the",
        "// units (zero-advance glyphs and the advancing glyph after them) last first, drawn where HarfBuzz's",
        "// left-to-right run draws them.",
        "",
        '#include "ArabicExpected.h"',
        "",
        "// clang-format off",
        f'constexpr const char* {fx.font_constant(FONT)} = "{FONT}";',
        "",
    ]
    pool, rows = [], []
    for text, glyphs in words_shaped:
        rows.append((text, len(pool), len(glyphs)))
        pool += glyphs
    lines.append("constexpr ExpectedGlyph kArabicNumberGlyphPool[] = {")
    for i in range(0, len(pool), 8):
        lines.append("    " + ",".join(f"{{{g},{a},{dx},{dy}}}" for g, a, dx, dy in pool[i:i + 8]) + ",")
    lines += ["};", "", "constexpr ArabicShapingExpectation kArabicNumberShaping[] = {"]
    for text, offset, count in rows:
        lines.append(f'    {{{fx.font_constant(FONT)}, "{fx.c_hex_string(text)}", "", kArabicNumberGlyphPool + {offset}, '
                     f'{count}}},')
    lines += ["};", "", "// clang-format on", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--fonts-out", type=Path, default=REPO / "test" / "fixtures" / "fonts")
    parser.add_argument("--header-out", type=Path, default=Path(__file__).resolve().parent / "ArabicNumberExpected.h")
    args = parser.parse_args()

    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    if digest != SOURCE_SHA256:
        sys.exit(f"{SOURCE}: sha256 {digest}, expected {SOURCE_SHA256}")
    codepoints = set(SIGNS) | {c for digits in DIGIT_SETS for c in digits} | {BEH, SPACE}
    data = fx.cut(SOURCE, codepoints)
    args.fonts_out.mkdir(parents=True, exist_ok=True)
    (args.fonts_out / FONT).write_bytes(data)

    font = fx.hb_font(data)
    shaped = []
    for text in words():
        written = units_reversed(raw_run(font, text, "rtl"))
        if placements(written) != placements(raw_run(font, text, "ltr")):
            sys.exit(f"{text!r}: the reversed right-to-left run is not drawn as HarfBuzz's left-to-right one")
        if as_expected(raw_run(font, text, "rtl")) != fx.shape(font, text, ""):
            sys.exit(f"{text!r}: the rounding differs from make_arabic_fixtures.shape()")
        shaped.append((text, as_expected(written)))
    args.header_out.write_text(header_text(shaped), encoding="utf-8")
    print(f"{FONT}: {len(data):,} B, {len(shaped)} words")


if __name__ == "__main__":
    main()
